# --- TOOL: .htaccess Generator ---
class HtaccessPayload(BaseModel):
    force_https: bool = False
    www_redirect: str = "none"
    enable_litespeed_cache: bool = False
    enable_cors: bool = False
    custom_redirects: Optional[List[dict]] = []

@app.post("/generate-htaccess")
def generate_htaccess(payload: HtaccessPayload):
    rules = ["# Generated by ChiralGrid"]
    if payload.force_https:
        rules.append("RewriteEngine On\nRewriteCond %{HTTPS} off\nRewriteRule ^(.*)$ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]")
    if payload.www_redirect == "force_www":
        rules.append("RewriteEngine On\nRewriteCond %{HTTP_HOST} !^www\\. [NC]\nRewriteRule ^(.*)$ https://www.%{HTTP_HOST}/$1 [R=301,L]")
    elif payload.www_redirect == "remove_www":
        rules.append("RewriteEngine On\nRewriteCond %{HTTP_HOST} ^www\\.(.*)$ [NC]\nRewriteRule ^(.*)$ https://%1/$1 [R=301,L]")
    if payload.enable_litespeed_cache:
        rules.append("<IfModule Litespeed>\nSetEnv LCACHE_BUF 1\n</IfModule>")
    if payload.enable_cors:
        rules.append('Header set Access-Control-Allow-Origin "*"')
    return {"htaccess_code": "\n\n".join(rules)}

# --- TOOL: Gemini AI Explanation Endpoint (Lazy Loaded) ---
class ExplainPayload(BaseModel):
    htaccess_code: str

@app.post("/api/v1/explain-htaccess")
async def explain_htaccess(payload: ExplainPayload):
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise HTTPException(
            status_code=500,
            detail="GEMINI_API_KEY environment variable is missing on Vercel."
        )

    if not payload.htaccess_code or not payload.htaccess_code.strip():
        raise HTTPException(status_code=400, detail="Please generate or paste .htaccess rules first.")

    try:
        from google import genai
        client = genai.Client(api_key=api_key)

        prompt = (
            "You are a web sysadmin. Explain these .htaccess rules in 2-3 plain English bullet points:\n\n"
            f"{payload.htaccess_code}"
        )
        response = client.models.generate_content(
            model="gemini-3.8-flash",
            contents=prompt
        )
        return {"explanation": response.text}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"AI Error: {str(e)}")



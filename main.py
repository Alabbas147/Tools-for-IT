# --- TOOL: Freelance Rate & Cost Estimator ---
class RatePayload(BaseModel):
    target_income: Optional[float] = 0.0
    hours_per_week: Optional[float] = 40.0
    vacation_weeks: Optional[float] = 2.0
    tax_rate: Optional[float] = 15.0
    rush_delivery: Optional[bool] = False

@app.post("/calculate-rate")
@app.post("/calculate-ai-cost")
@app.post("/estimate-project")
def calculate_rate(payload: RatePayload):
    working_weeks = max(1.0, 52.0 - payload.vacation_weeks)
    total_hours = working_weeks * payload.hours_per_week
    if total_hours <= 0:
        raise HTTPException(status_code=400, detail="Working hours must be greater than zero.")

    tax_factor = max(0.01, 1.0 - (payload.tax_rate / 100.0))
    gross_needed = payload.target_income / tax_factor
    base_rate = gross_needed / total_hours

    if payload.rush_delivery:
        base_rate *= 1.30

    return {
        "hourly_rate": round(base_rate, 2),
        "total_billable_hours": round(total_hours, 1),
        "gross_income_needed": round(gross_needed, 2)
    }

